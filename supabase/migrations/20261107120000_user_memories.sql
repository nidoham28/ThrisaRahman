--  user memories
--
--  Persistent long-term memories the AI assistant stores about the user.
--  Rows are keyed by `uuid` (the app's cross-device sync id); `id` is the
--  numeric id the assistant's memory tools reference. One row per user fact.

create table if not exists public.user_memories (
  id bigint generated by default as identity,
  uid uuid not null,
  uuid text not null,
  content text not null,
  category text not null default 'general',
  importance integer not null default 3,
  tags text[] not null default array[]::text[],
  source text not null default 'ai_tool',
  create_at timestamptz not null default now(),
  update_at timestamptz not null default now(),
  constraint user_memories_pkey primary key (id),
  constraint user_memories_uid_fkey foreign key (uid)
    references public.user_profiles (id) on delete cascade,
  constraint user_memories_uuid_key unique (uuid),
  constraint user_memories_content_check check (length(btrim(content)) > 0),
  constraint user_memories_category_check check (category in (
    'profile', 'preference', 'fact', 'work',
    'relationship', 'health', 'goal', 'general'
  )),
  constraint user_memories_importance_check check (importance between 1 and 5),
  constraint user_memories_source_check check (source in ('ai_tool', 'user_manual', 'system'))
);

create index if not exists user_memories_uid_update_at_idx
  on public.user_memories (uid, update_at desc);
create index if not exists user_memories_uid_category_idx
  on public.user_memories (uid, category);
create index if not exists user_memories_tags_idx
  on public.user_memories using gin (tags);

create or replace function public.user_memories_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and (
    new.id is distinct from old.id
    or new.uid is distinct from old.uid
    or new.uuid is distinct from old.uuid
    or new.create_at is distinct from old.create_at
  ) then
    raise exception 'Memory identity, owner and creation time are immutable';
  end if;

  if tg_op = 'UPDATE' then
    new.update_at := now();
    new.content := btrim(new.content);
    if length(new.content) = 0 then
      raise exception 'Memory content must not be blank';
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists trg_user_memories_guard on public.user_memories;
create trigger trg_user_memories_guard
  before insert or update on public.user_memories
  for each row execute function public.user_memories_guard();

alter table public.user_memories enable row level security;

drop policy if exists user_memories_select_own on public.user_memories;
create policy user_memories_select_own on public.user_memories
  for select to authenticated
  using (uid = (select auth.uid()));

drop policy if exists user_memories_insert_own on public.user_memories;
create policy user_memories_insert_own on public.user_memories
  for insert to authenticated
  with check (uid = (select auth.uid()));

drop policy if exists user_memories_update_own on public.user_memories;
create policy user_memories_update_own on public.user_memories
  for update to authenticated
  using (uid = (select auth.uid()))
  with check (uid = (select auth.uid()));

drop policy if exists user_memories_delete_own on public.user_memories;
create policy user_memories_delete_own on public.user_memories
  for delete to authenticated
  using (uid = (select auth.uid()));

revoke all on public.user_memories from anon, authenticated;

-- Table-level grants: PostgREST upserts (INSERT … ON CONFLICT … RETURNING *)
-- require SELECT/UPDATE/INSERT across every column, so column-level grants
-- break the generated SQL. RLS policies remain the row-level boundary.
grant select, insert, update, delete on public.user_memories to authenticated;

notify pgrst, 'reload schema';
