--  user provider keys
--
--  API keys for the assistant's model providers, stored per account so every
--  signed-in device picks them up. One row per (user, provider).

create table if not exists public.user_provider_keys (
  id bigint generated by default as identity,
  uid uuid not null,
  provider text not null,
  api_key text not null,
  create_at timestamptz not null default now(),
  update_at timestamptz not null default now(),
  constraint user_provider_keys_pkey primary key (id),
  constraint user_provider_keys_uid_fkey foreign key (uid)
    references public.user_profiles (id) on delete cascade,
  constraint user_provider_keys_uid_provider_key unique (uid, provider),
  constraint user_provider_keys_provider_check check (provider in (
    'gemini', 'openrouter'
  )),
  constraint user_provider_keys_api_key_check check (length(btrim(api_key)) > 0)
);

create or replace function public.user_provider_keys_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and (
    new.id is distinct from old.id
    or new.uid is distinct from old.uid
    or new.provider is distinct from old.provider
    or new.create_at is distinct from old.create_at
  ) then
    raise exception 'Provider key identity, owner and provider are immutable';
  end if;

  if tg_op = 'UPDATE' then
    new.update_at := now();
    if length(btrim(new.api_key)) = 0 then
      raise exception 'Provider key must not be blank';
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists trg_user_provider_keys_guard on public.user_provider_keys;
create trigger trg_user_provider_keys_guard
  before insert or update on public.user_provider_keys
  for each row execute function public.user_provider_keys_guard();

alter table public.user_provider_keys enable row level security;

drop policy if exists user_provider_keys_select_own on public.user_provider_keys;
create policy user_provider_keys_select_own on public.user_provider_keys
  for select to authenticated
  using (uid = (select auth.uid()));

drop policy if exists user_provider_keys_insert_own on public.user_provider_keys;
create policy user_provider_keys_insert_own on public.user_provider_keys
  for insert to authenticated
  with check (uid = (select auth.uid()));

drop policy if exists user_provider_keys_update_own on public.user_provider_keys;
create policy user_provider_keys_update_own on public.user_provider_keys
  for update to authenticated
  using (uid = (select auth.uid()))
  with check (uid = (select auth.uid()));

drop policy if exists user_provider_keys_delete_own on public.user_provider_keys;
create policy user_provider_keys_delete_own on public.user_provider_keys
  for delete to authenticated
  using (uid = (select auth.uid()));

revoke all on public.user_provider_keys from anon, authenticated;

-- Table-level grants: PostgREST upserts (INSERT … ON CONFLICT … RETURNING *)
-- require SELECT/UPDATE/INSERT across every column, so column-level grants
-- break the generated SQL. RLS policies remain the row-level boundary.
grant select, insert, update, delete on public.user_provider_keys to authenticated;

notify pgrst, 'reload schema';
