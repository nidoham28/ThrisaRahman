--  user schedule
--
--  AI-managed reminders and scheduled events. The device keeps firing them
--  locally; this table makes them available on every signed-in device.
--  Rows are keyed by `uuid` (the app's cross-device sync id); `id` is the
--  numeric id the assistant's reminder tools reference.

create table if not exists public.user_schedule (
  id bigint generated by default as identity,
  uid uuid not null,
  uuid text not null,
  title text not null,
  description text not null default '',
  trigger_at timestamptz not null,
  recurrence text not null default 'none',
  recurrence_interval integer not null default 0,
  status text not null default 'active',
  priority text not null default 'normal',
  tags text[] not null default array[]::text[],
  snoozed_until timestamptz,
  next_trigger_at timestamptz not null,
  source text not null default 'ai_tool',
  create_at timestamptz not null default now(),
  update_at timestamptz not null default now(),
  constraint user_schedule_pkey primary key (id),
  constraint user_schedule_uid_fkey foreign key (uid)
    references public.user_profiles (id) on delete cascade,
  constraint user_schedule_uuid_key unique (uuid),
  constraint user_schedule_title_check check (length(btrim(title)) > 0),
  constraint user_schedule_recurrence_check check (recurrence in (
    'none', 'daily', 'weekly', 'monthly', 'yearly',
    'weekdays', 'weekends', 'custom'
  )),
  constraint user_schedule_interval_check check (recurrence_interval >= 0),
  constraint user_schedule_status_check check (status in (
    'active', 'done', 'snoozed', 'cancelled'
  )),
  constraint user_schedule_priority_check check (priority in (
    'low', 'normal', 'high', 'urgent'
  )),
  constraint user_schedule_source_check check (source in ('ai_tool', 'user_manual', 'system')),
  constraint user_schedule_next_trigger_check check (next_trigger_at >= trigger_at)
);

create index if not exists user_schedule_uid_next_trigger_idx
  on public.user_schedule (uid, next_trigger_at);
create index if not exists user_schedule_uid_status_idx
  on public.user_schedule (uid, status);
create index if not exists user_schedule_tags_idx
  on public.user_schedule using gin (tags);

create or replace function public.user_schedule_guard()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' and (
    new.id is distinct from old.id
    or new.uid is distinct from old.uid
    or new.uuid is distinct from old.uuid
    or new.create_at is distinct from old.create_at
  ) then
    raise exception 'Schedule identity, owner and creation time are immutable';
  end if;

  if tg_op = 'UPDATE' then
    new.update_at := now();
    new.title := btrim(new.title);
    if length(new.title) = 0 then
      raise exception 'Schedule title must not be blank';
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists trg_user_schedule_guard on public.user_schedule;
create trigger trg_user_schedule_guard
  before insert or update on public.user_schedule
  for each row execute function public.user_schedule_guard();

alter table public.user_schedule enable row level security;

drop policy if exists user_schedule_select_own on public.user_schedule;
create policy user_schedule_select_own on public.user_schedule
  for select to authenticated
  using (uid = (select auth.uid()));

drop policy if exists user_schedule_insert_own on public.user_schedule;
create policy user_schedule_insert_own on public.user_schedule
  for insert to authenticated
  with check (uid = (select auth.uid()));

drop policy if exists user_schedule_update_own on public.user_schedule;
create policy user_schedule_update_own on public.user_schedule
  for update to authenticated
  using (uid = (select auth.uid()))
  with check (uid = (select auth.uid()));

drop policy if exists user_schedule_delete_own on public.user_schedule;
create policy user_schedule_delete_own on public.user_schedule
  for delete to authenticated
  using (uid = (select auth.uid()));

revoke all on public.user_schedule from anon, authenticated;

-- Table-level grants: PostgREST upserts (INSERT … ON CONFLICT … RETURNING *)
-- require SELECT/UPDATE/INSERT across every column, so column-level grants
-- break the generated SQL. RLS policies remain the row-level boundary.
grant select, insert, update, delete on public.user_schedule to authenticated;

notify pgrst, 'reload schema';
